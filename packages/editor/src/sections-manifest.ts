import fs from 'node:fs'
import path from 'node:path'

/** The two files `bearminion sync` writes next to the section directories. */
export const DEFINITIONS_FILE = 'definitions.gen.ts'
export const COMPONENTS_FILE = 'components.gen.ts'

/** One section directory: `logo-strip/` holds `definition.ts` (exporting `logoStrip`) and `LogoStrip.astro`. */
export interface SectionEntry {
  /** Directory name, in kebab-case. */
  dir: string
  /** The section `type`, the export name of its definition: the directory name in camelCase. */
  key: string
  /** The default export of its component, and the file name without `.astro`: the directory name in PascalCase. */
  component: string
}

/** A section directory that does not follow the convention. The message says what to fix. */
export class SectionsError extends Error {}

const DIRECTORY_NAME = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/

export const toCamelCase = (dir: string): string => dir.replace(/-([a-z0-9])/g, (_, char: string) => char.toUpperCase())
export const toPascalCase = (dir: string): string => {
  const camel = toCamelCase(dir)
  return camel.charAt(0).toUpperCase() + camel.slice(1)
}

/**
 * Lists the section directories: every folder under `sectionsDir` that holds a `definition.ts`. Folders that start
 * with `_` or `.` and folders without a definition are not sections. Sorted by name, so the result never depends on
 * the file system.
 */
export function scanSections(sectionsDir: string): SectionEntry[] {
  if (!fs.existsSync(sectionsDir)) throw new SectionsError(`No sections folder at ${sectionsDir}.`)
  const entries: SectionEntry[] = []
  for (const child of fs.readdirSync(sectionsDir, { withFileTypes: true })) {
    if (!child.isDirectory() || child.name.startsWith('_') || child.name.startsWith('.')) continue
    if (!fs.existsSync(path.join(sectionsDir, child.name, 'definition.ts'))) continue
    if (!DIRECTORY_NAME.test(child.name)) {
      throw new SectionsError(
        `"${child.name}" is not a usable section name. Use lowercase words joined by hyphens, such as "logo-strip": the directory name becomes the section type.`,
      )
    }
    const component = toPascalCase(child.name)
    if (!fs.existsSync(path.join(sectionsDir, child.name, `${component}.astro`))) {
      throw new SectionsError(`${child.name}/ has a definition.ts but no ${component}.astro. The component is named after the directory.`)
    }
    entries.push({ dir: child.name, key: toCamelCase(child.name), component })
  }
  if (entries.length === 0) throw new SectionsError(`No sections found in ${sectionsDir}. A section is a directory with a definition.ts.`)
  return entries.sort((a, b) => (a.dir < b.dir ? -1 : a.dir > b.dir ? 1 : 0))
}

const HEADER = '// Generated by `bearminion sync`. Do not edit: add or remove a directory under sections/ and run it again.'

/** The contents of `definitions.gen.ts`: schemas only, no `.astro` imports, so `astro.config.ts` and the editor can load it. */
export function renderDefinitions(entries: readonly SectionEntry[]): string {
  const imports = entries.map((entry) => `import { ${entry.key} } from './${entry.dir}/definition'`)
  const keys = entries.map((entry) => `  ${entry.key},`)
  return [
    HEADER,
    "import type { SectionRegistry } from 'bearminion'",
    ...imports,
    '',
    'export const sectionDefinitions = {',
    ...keys,
    '} satisfies SectionRegistry',
    '',
  ].join('\n')
}

/** The contents of `components.gen.ts`: the section type to the component that renders it. */
export function renderComponents(entries: readonly SectionEntry[]): string {
  const imports = entries.map((entry) => `import ${entry.component} from './${entry.dir}/${entry.component}.astro'`)
  const map = entries.map((entry) => `  ${entry.key}: ${entry.component},`)
  return [
    HEADER,
    "import type { SectionType } from './definitions'",
    ...imports,
    '',
    '/** Maps a content section `type` to the component that renders it. */',
    'export const sectionComponents = {',
    ...map,
    '} satisfies Record<SectionType, unknown>',
    '',
  ].join('\n')
}

export interface SyncResult {
  /** The generated files that differ from what the directories call for (written, unless `check`). */
  changed: string[]
  entries: SectionEntry[]
}

/**
 * Makes `definitions.gen.ts` and `components.gen.ts` match the section directories. With `check` it only reports
 * which files are stale and writes nothing.
 */
export function syncSections(sectionsDir: string, options: { check?: boolean } = {}): SyncResult {
  const entries = scanSections(sectionsDir)
  const wanted: Record<string, string> = {
    [DEFINITIONS_FILE]: renderDefinitions(entries),
    [COMPONENTS_FILE]: renderComponents(entries),
  }
  const changed: string[] = []
  for (const [file, content] of Object.entries(wanted)) {
    const target = path.join(sectionsDir, file)
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : undefined
    if (current === content) continue
    changed.push(file)
    if (!options.check) fs.writeFileSync(target, content)
  }
  return { changed, entries }
}

/** The sentence for a build that stops on stale files, or for the dev server's warning. */
export function staleSectionsMessage(changed: readonly string[]): string {
  return `${changed.join(' and ')} no longer match the directories under sections/. Run \`npx bearminion sync\`.`
}
