import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { run } from '../src/command.js'
import { bearminion } from '../src/integration.js'
import {
  COMPONENTS_FILE,
  DEFINITIONS_FILE,
  renderComponents,
  renderDefinitions,
  scanSections,
  SectionsError,
  staleSectionsMessage,
  syncSections,
  toCamelCase,
  toPascalCase,
} from '../src/sections-manifest.js'
import { contentModel } from './starter.js'

const temporary: string[] = []

/** A sections folder with the named directories, each holding a definition and its component. */
function sectionsFolder(dirs: readonly string[], extra: (root: string) => void = () => {}): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'bearminion-sections-'))
  temporary.push(root)
  for (const dir of dirs) {
    fs.mkdirSync(path.join(root, dir), { recursive: true })
    fs.writeFileSync(path.join(root, dir, 'definition.ts'), '')
    fs.writeFileSync(path.join(root, dir, `${toPascalCase(dir)}.astro`), '')
  }
  extra(root)
  return root
}

afterEach(() => {
  for (const dir of temporary.splice(0)) fs.rmSync(dir, { recursive: true, force: true })
})

describe('names', () => {
  it('turns a directory name into the section type and the component name', () => {
    expect(toCamelCase('logo-strip')).toBe('logoStrip')
    expect(toPascalCase('logo-strip')).toBe('LogoStrip')
    expect(toCamelCase('hero')).toBe('hero')
    expect(toPascalCase('text-image')).toBe('TextImage')
  })
})

describe('scanSections', () => {
  it('lists the directories that hold a definition, sorted by name', () => {
    const root = sectionsFolder(['text-image', 'hero', 'faq'])
    expect(scanSections(root)).toEqual([
      { dir: 'faq', key: 'faq', component: 'Faq' },
      { dir: 'hero', key: 'hero', component: 'Hero' },
      { dir: 'text-image', key: 'textImage', component: 'TextImage' },
    ])
  })

  it('leaves out folders that are not sections: no definition, a leading underscore or dot', () => {
    const root = sectionsFolder(['hero'], (folder) => {
      fs.mkdirSync(path.join(folder, 'shared-bits'))
      fs.mkdirSync(path.join(folder, '_draft'))
      fs.writeFileSync(path.join(folder, '_draft', 'definition.ts'), '')
      fs.mkdirSync(path.join(folder, '.cache'))
      fs.writeFileSync(path.join(folder, '.cache', 'definition.ts'), '')
      fs.writeFileSync(path.join(folder, 'shared.ts'), '')
    })
    expect(scanSections(root).map((entry) => entry.dir)).toEqual(['hero'])
  })

  it('names the directory that does not fit the convention', () => {
    const root = sectionsFolder([], (folder) => {
      fs.mkdirSync(path.join(folder, 'LogoStrip'))
      fs.writeFileSync(path.join(folder, 'LogoStrip', 'definition.ts'), '')
    })
    expect(() => scanSections(root)).toThrow(/"LogoStrip" is not a usable section name/)
  })

  it('names the component a section is missing', () => {
    const root = sectionsFolder(['hero'])
    fs.rmSync(path.join(root, 'hero', 'Hero.astro'))
    expect(() => scanSections(root)).toThrow(/hero\/ has a definition\.ts but no Hero\.astro/)
  })

  it('refuses an empty or missing folder', () => {
    expect(() => scanSections(sectionsFolder([]))).toThrow(SectionsError)
    expect(() => scanSections(path.join(os.tmpdir(), 'bearminion-no-such-sections'))).toThrow(/No sections folder/)
  })
})

describe('the generated files', () => {
  const entries = [
    { dir: 'hero', key: 'hero', component: 'Hero' },
    { dir: 'logo-strip', key: 'logoStrip', component: 'LogoStrip' },
  ]

  it('list every definition without importing a component', () => {
    const text = renderDefinitions(entries)
    expect(text).toContain("import { hero } from './hero/definition'")
    expect(text).toContain("import { logoStrip } from './logo-strip/definition'")
    expect(text).toContain('} satisfies SectionRegistry')
    expect(text).not.toContain('.astro')
  })

  it('map every type to its component', () => {
    const text = renderComponents(entries)
    expect(text).toContain("import LogoStrip from './logo-strip/LogoStrip.astro'")
    expect(text).toContain('  logoStrip: LogoStrip,')
    expect(text).toContain('} satisfies Record<SectionType, unknown>')
  })

  it('say they are generated', () => {
    expect(renderDefinitions(entries).startsWith('// Generated by `bearminion sync`.')).toBe(true)
    expect(renderComponents(entries).startsWith('// Generated by `bearminion sync`.')).toBe(true)
  })
})

describe('syncSections', () => {
  it('writes both files, and writes nothing the second time', () => {
    const root = sectionsFolder(['hero', 'faq'])
    expect(syncSections(root).changed).toEqual([DEFINITIONS_FILE, COMPONENTS_FILE])
    expect(fs.readFileSync(path.join(root, DEFINITIONS_FILE), 'utf8')).toContain("import { faq } from './faq/definition'")
    expect(syncSections(root).changed).toEqual([])
  })

  it('reports stale files in check mode and does not touch them', () => {
    const root = sectionsFolder(['hero'])
    syncSections(root)
    fs.mkdirSync(path.join(root, 'faq'))
    fs.writeFileSync(path.join(root, 'faq', 'definition.ts'), '')
    fs.writeFileSync(path.join(root, 'faq', 'Faq.astro'), '')
    const before = fs.readFileSync(path.join(root, DEFINITIONS_FILE), 'utf8')
    expect(syncSections(root, { check: true }).changed).toEqual([DEFINITIONS_FILE, COMPONENTS_FILE])
    expect(fs.readFileSync(path.join(root, DEFINITIONS_FILE), 'utf8')).toBe(before)
    syncSections(root)
    expect(syncSections(root, { check: true }).changed).toEqual([])
  })

  it('treats a missing generated file as stale', () => {
    const root = sectionsFolder(['hero'])
    expect(syncSections(root, { check: true }).changed).toEqual([DEFINITIONS_FILE, COMPONENTS_FILE])
  })

  it('puts a removed directory out of the files', () => {
    const root = sectionsFolder(['hero', 'faq'])
    syncSections(root)
    fs.rmSync(path.join(root, 'faq'), { recursive: true })
    expect(syncSections(root).changed).toEqual([DEFINITIONS_FILE, COMPONENTS_FILE])
    expect(fs.readFileSync(path.join(root, COMPONENTS_FILE), 'utf8')).not.toContain('Faq')
  })

  it('words the stale message for a build', () => {
    expect(staleSectionsMessage([DEFINITIONS_FILE])).toBe(
      'definitions.gen.ts no longer match the directories under sections/. Run `npx bearminion sync`.',
    )
  })
})

describe('bearminion sync', () => {
  const lines = (root: string, argv: string[]) => {
    const out: string[] = []
    const code = run(argv, (line) => out.push(line))
    return { code, text: out.join('\n'), root }
  }

  it('writes the files, then says they are in sync', () => {
    const root = sectionsFolder(['hero', 'faq'])
    expect(lines(root, ['sync', '--sections', root])).toMatchObject({
      code: 0,
      text: 'Wrote definitions.gen.ts and components.gen.ts (2 sections).',
    })
    expect(lines(root, ['sync', '--sections', root])).toMatchObject({ code: 0, text: 'Already in sync (2 sections).' })
  })

  it('--check exits 1 for stale files, and writes nothing', () => {
    const root = sectionsFolder(['hero'])
    const stale = lines(root, ['sync', '--check', '--sections', root])
    expect(stale.code).toBe(1)
    expect(stale.text).toContain('Run `npx bearminion sync`')
    expect(fs.existsSync(path.join(root, DEFINITIONS_FILE))).toBe(false)
    syncSections(root)
    expect(lines(root, ['sync', '--check', '--sections', root])).toMatchObject({ code: 0 })
  })

  it('resolves the folder from --cwd and the default sections path', () => {
    const project = fs.mkdtempSync(path.join(os.tmpdir(), 'bearminion-project-'))
    temporary.push(project)
    const sections = path.join(project, 'src', 'components', 'sections')
    fs.mkdirSync(path.join(sections, 'hero'), { recursive: true })
    fs.writeFileSync(path.join(sections, 'hero', 'definition.ts'), '')
    fs.writeFileSync(path.join(sections, 'hero', 'Hero.astro'), '')
    expect(lines(project, ['sync', '--cwd', project]).code).toBe(0)
    expect(fs.existsSync(path.join(sections, DEFINITIONS_FILE))).toBe(true)
  })

  it('reports a section that breaks the convention, and unknown commands', () => {
    const root = sectionsFolder(['hero'])
    fs.rmSync(path.join(root, 'hero', 'Hero.astro'))
    expect(lines(root, ['sync', '--sections', root])).toMatchObject({ code: 1 })
    expect(lines(root, ['frobnicate']).code).toBe(2)
    expect(lines(root, ['sync', '--nope']).code).toBe(2)
    expect(lines(root, []).code).toBe(2)
    expect(lines(root, ['--help']).code).toBe(0)
  })
})

describe('the integration check', () => {
  const setup = (command: 'dev' | 'build', sectionsDir: string | undefined, root: string, logger = { warn: vi.fn() }) => {
    const integration = bearminion({ ...contentModel, ...(sectionsDir !== undefined ? { sectionsDir } : {}) })
    const hook = integration.hooks['astro:config:setup']
    const calls = { update: vi.fn(), script: vi.fn() }
    const run = () =>
      hook?.({
        command,
        config: { root },
        logger,
        updateConfig: calls.update,
        injectScript: calls.script,
      } as never)
    return { run, logger }
  }

  it('stops a build when the generated files are stale', async () => {
    const root = sectionsFolder(['hero'])
    const { run: build } = setup('build', '.', root)
    await expect(Promise.resolve().then(build)).rejects.toThrow(/Run `npx bearminion sync`/)
    syncSections(root)
    await expect(Promise.resolve().then(build)).resolves.toBeUndefined()
  })

  it('only warns in astro dev', async () => {
    const root = sectionsFolder(['hero'])
    const { run: dev, logger } = setup('dev', '.', root)
    await dev()
    expect(logger.warn).toHaveBeenCalledWith(expect.stringContaining('Run `npx bearminion sync`'))
  })

  it('checks nothing unless sectionsDir is set', async () => {
    const { run: build } = setup('build', undefined, path.join(os.tmpdir(), 'bearminion-no-such-project'))
    await expect(Promise.resolve().then(build)).resolves.toBeUndefined()
  })
})
