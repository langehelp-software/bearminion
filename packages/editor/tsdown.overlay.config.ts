import { readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { defineConfig } from 'tsdown'

/** `import css from './file.css?raw'`: the file's text, as the main build does it. */
const raw = {
  name: 'bearminion:raw',
  resolveId(id: string, importer?: string) {
    if (!id.endsWith('?raw') || !importer) return null
    return `${path.resolve(path.dirname(importer), id.slice(0, -'?raw'.length))}?raw`
  },
  load(id: string) {
    if (!id.endsWith('?raw')) return null
    return `export default ${JSON.stringify(readFileSync(id.slice(0, -'?raw'.length), 'utf8'))}`
  },
}

/**
 * The editor overlay as one browser script, for the hosted editor: unlike `dist/ui/mount.js` (which the dev server
 * loads, and which leaves `preact` for Vite to resolve), nothing is left to resolve, because a hosted page has no
 * Vite. The script is then wrapped as `dist/hosted-overlay.js`, a module exporting its source as a string, so a Worker
 * can serve it without reading files. Runs after the main build (`npm run build`), which empties `dist/` first.
 */
export default defineConfig({
  entry: { 'ui/hosted': 'src/ui/hosted.tsx' },
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  tsconfig: 'tsconfig.build.json',
  dts: false,
  clean: false,
  minify: true,
  sourcemap: false,
  deps: { alwaysBundle: [/.*/], neverBundle: [] },
  plugins: [raw],
  onSuccess: () => {
    const script = path.resolve('dist/ui/hosted.js')
    const source = readFileSync(script, 'utf8')
    writeFileSync(
      path.resolve('dist/hosted-overlay.js'),
      `// Generated by tsdown.overlay.config.ts. The editor overlay as one browser script.\nexport const overlaySource = ${JSON.stringify(source)}\n`,
    )
    writeFileSync(
      path.resolve('dist/hosted-overlay.d.ts'),
      '/** The editor overlay as one self-contained browser script (an ES module that mounts itself). */\nexport declare const overlaySource: string\n',
    )
    rmSync(script)
  },
})
